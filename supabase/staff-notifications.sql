-- ===================== SMS LOG =====================

CREATE TABLE IF NOT EXISTS public.sms_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_phone varchar(30) NOT NULL,
  content text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'sent',
  error_message text DEFAULT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sms_logs_created_at ON public.sms_logs (created_at);

-- ===================== DEDUP / SEND LEDGER =====================
-- One row per (leave, event) so the daily cron never double-sends.

CREATE TABLE IF NOT EXISTS public.staff_notification_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  leave_id bigint NOT NULL,
  event varchar(20) NOT NULL,          -- 'start' | 'returned'
  sent_at timestamptz DEFAULT now(),
  CONSTRAINT staff_notification_log_leave_event_key UNIQUE (leave_id, event)
);

CREATE INDEX IF NOT EXISTS idx_staff_notification_log_leave_id
  ON public.staff_notification_log (leave_id);

ALTER TABLE public.sms_logs DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.staff_notification_log DISABLE ROW LEVEL SECURITY;

